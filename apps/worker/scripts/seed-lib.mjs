// Plain-JS twin of the shared question import rules (packages/shared/src/quiz/import.ts and
// src/text.ts), so `seed.mjs` runs on bare Node without a TS build. A test asserts both agree.
export const LIMITS = { theme: 40, question: 300, answer: 100, variants: 10, variant: 100 };

export function normalize(s) {
  return s
    .toLowerCase()
    .replace(/œ/g, 'oe')
    .replace(/æ/g, 'ae')
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .replace(/[-'’_]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

export function questionKey(q) {
  return normalize(q).replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
}

const LABELS = { theme: 'le thème', question: 'la question', answer: 'la réponse' };
const isObject = (v) => typeof v === 'object' && v !== null && !Array.isArray(v);

function requiredText(src, key) {
  const v = src[key];
  if (typeof v !== 'string') throw new Error(`${LABELS[key]} doit être un texte`);
  const s = v.normalize('NFC').trim();
  if (!s) throw new Error(`${LABELS[key]} est vide`);
  if (s.length > LIMITS[key]) throw new Error(`${LABELS[key]} dépasse ${LIMITS[key]} caractères`);
  return s;
}

function variantsOf(v) {
  if (v === undefined) return [];
  if (!Array.isArray(v) || v.some((x) => typeof x !== 'string')) throw new Error('les variantes doivent être une liste de textes');
  const out = v.map((x) => x.normalize('NFC').trim()).filter((x) => x.length > 0);
  if (out.length > LIMITS.variants) throw new Error(`plus de ${LIMITS.variants} variantes`);
  if (out.some((x) => x.length > LIMITS.variant)) throw new Error(`une variante dépasse ${LIMITS.variant} caractères`);
  return out;
}

/** Same contract as the shared parseImport: `{ ok, errors: [{index, reason}] }`. */
export function parseImport(json) {
  if (!isObject(json) || !Array.isArray(json.questions)) {
    return { ok: [], errors: [{ index: -1, reason: 'le fichier doit contenir {"questions": [...]}' }] };
  }
  const ok = [];
  const errors = [];
  json.questions.forEach((item, index) => {
    if (!isObject(item)) {
      errors.push({ index, reason: 'la question doit être un objet' });
      return;
    }
    try {
      ok.push({
        theme: requiredText(item, 'theme'),
        question: requiredText(item, 'question'),
        answer: requiredText(item, 'answer'),
        variants: variantsOf(item.variants),
      });
    } catch (err) {
      errors.push({ index, reason: err.message });
    }
  });
  return { ok, errors };
}

/** SQL string literal; D1 (SQLite) only needs single quotes doubled. NUL bytes are dropped. */
export const sqlString = (s) => `'${String(s).replace(/\0/g, '').replace(/'/g, "''")}'`;

/**
 * INSERT OR IGNORE statements (one per row, so re-runs skip existing rows). Entries that fail
 * validation are skipped and reported; questions with a duplicate key inside the file are
 * left to the UNIQUE constraint (the first wins).
 */
export function buildSql({ questions, words = [], source = 'généré', now = Date.now() }) {
  const { ok, errors } = parseImport(questions);
  const lines = ['-- generated by apps/worker/scripts/seed.mjs'];
  for (const q of ok) {
    lines.push(
      `INSERT OR IGNORE INTO questions (theme, question, question_key, answer, variants, source, created_at) VALUES (` +
        [sqlString(q.theme), sqlString(q.question), sqlString(questionKey(q.question)), sqlString(q.answer), sqlString(JSON.stringify(q.variants)), sqlString(source), Math.trunc(now)].join(', ') +
        ');',
    );
  }
  const seen = new Set();
  let wordCount = 0;
  for (const w of words) {
    if (typeof w !== 'string' || !w.trim() || seen.has(w)) continue;
    seen.add(w);
    wordCount++;
    lines.push(`INSERT OR IGNORE INTO words (word) VALUES (${sqlString(w.trim())});`);
  }
  return { sql: lines.join('\n') + '\n', questionCount: ok.length, wordCount, errors };
}
